export type MemoPresentationCopy = (typeof memoPresentationCopy)[AppLocale];
export type MemoPresentationKey = keyof MemoPresentationCopy;

export function getMemoPresentationCopy(locale: AppLocale): MemoPresentationCopy {
  return memoPresentationCopy[locale];
}

export function translateMemoPresentation(
  locale: AppLocale,
  key: MemoPresentationKey,
  values?: MessageValues,
) {
  const template = memoPresentationCopy[locale][key];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

