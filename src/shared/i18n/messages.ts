export const messagesByLocale: Record<AppLocale, Record<MessageKey, string>> = {
  "zh-CN": zhCN,
  "it-IT": itIT,
  en,
};

export function translateMessage(locale: AppLocale, key: MessageKey, values?: MessageValues) {
  const template = messagesByLocale[locale][key] ?? zhCN[key];
  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}
