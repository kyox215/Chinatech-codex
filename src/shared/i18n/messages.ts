export type SettingsOperationsMessage =
  | keyof typeof settingsOperationsTranslations
  | keyof typeof settingsBusinessTranslations;

export function translateSettingsOperations(
  locale: AppLocale,
  source: SettingsOperationsMessage,
  values?: MessageValues,
) {
  const translations =
    source in settingsBusinessTranslations
      ? settingsBusinessTranslations[source as keyof typeof settingsBusinessTranslations]
      : settingsOperationsTranslations[source as keyof typeof settingsOperationsTranslations];
  const template = locale === "zh-CN" ? source : translations[locale === "it-IT" ? 0 : 1];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

